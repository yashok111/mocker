import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const contract = JSON.parse(
  await readFile(new URL("../../api/openapi.json", import.meta.url), "utf8"),
);
const roots = [
  "BackendChangeProposalCommand",
  "CreateBackendChangeProposalRequest",
  "PreviewBackendChangeProposalCommandsRequest",
  "ApplyBackendChangeProposalCommandsRequest",
  "RestoreBackendChangeProposalRequest",
  "StartBackendAnalysisRequest",
  "CancelBackendAnalysisRequest",
  "RetryBackendAnalysisRequest",
  "PreviewBackendChangeProposalRebaseRequest",
  "ApplyBackendChangeProposalRebaseRequest",
  "ApplyBackendChangeProposalLifecycleRequest",
  "BackendAnalysisJobDetail",
  "BackendAnalysisResultPage",
  "BackendChangeProposalApplyResult",
  "BackendChangeProposalLifecycleEventV1",
];
const definitions = {};
function include(name) {
  if (Object.hasOwn(definitions, name)) return;
  const schema = contract.components.schemas[name];
  if (!schema) throw new Error(`Missing canonical schema ${name}`);
  definitions[name] = schema;
  function walk(value) {
    if (Array.isArray(value)) {
      value.forEach(walk);
      return;
    }
    if (value === null || typeof value !== "object") return;
    if (typeof value.$ref === "string") include(value.$ref.slice("#/components/schemas/".length));
    Object.values(value).forEach(walk);
  }
  walk(schema);
}
roots.forEach(include);
const sorted = Object.fromEntries(
  Object.entries(definitions).sort(([left], [right]) => left.localeCompare(right, "en")),
);
const output = new URL(
  "../src/components/backend-workbench/backendChangeSchema.ts",
  import.meta.url,
);
await writeFile(
  output,
  `// Generated by node web/scripts/generate-backend-change-schema.mjs.
/* oxlint-disable unicorn/no-thenable -- JSON Schema then is non-callable data. */\n// Canonical source: api/openapi.json. Do not edit manually.\nimport type { ChangeSchema } from "./backendChangeSchemaTypes";\n\nexport const backendChangeSchemas: Record<string, ChangeSchema> = ${JSON.stringify(sorted, null, 2)};\n`,
);
execFileSync(
  fileURLToPath(new URL("../node_modules/.bin/oxfmt", import.meta.url)),
  ["--write", fileURLToPath(output)],
  { cwd: fileURLToPath(new URL("../", import.meta.url)), stdio: "pipe" },
);
console.log(
  `Wrote ${Object.keys(sorted).length} command schema definitions to ${fileURLToPath(output)}`,
);
